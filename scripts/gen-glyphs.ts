/** Writes src/render/glyphs.ts: the code point ranges of the vendored font's cmap (`npm run font:glyphs`). A test compares the committed file with the font. */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { glyphRangesOfFont } from '../src/render/glyphRanges.js';

const ranges = glyphRangesOfFont(fileURLToPath(new URL('../src/render/fonts/Inter.ttf', import.meta.url)));
const body = ranges.map(([a, b]) => `  [0x${a.toString(16)}, 0x${b.toString(16)}],`).join('\n');
writeFileSync(
  new URL('../src/render/glyphs.ts', import.meta.url),
  `// Generated by scripts/gen-glyphs.ts from src/render/fonts/Inter.ttf: do not edit. Inclusive code point ranges the font has a glyph for.\nexport const GLYPH_RANGES: readonly (readonly [number, number])[] = [\n${body}\n];\n`,
);
console.log(`${ranges.length} ranges`);
